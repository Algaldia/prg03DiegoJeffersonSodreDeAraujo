class BotaoRenderer extends JButton
        implements TableCellRenderer {

    public BotaoRenderer() {
        setOpaque(true);
    }

    @Override
    public Component getTableCellRendererComponent(
            JTable tabela, Object valor,
            boolean selecionado, boolean foco,
            int linha, int coluna) {

        setText(valor == null ? "" : valor.toString());
        return this;
    }
}

class BotaoEditor extends AbstractCellEditor
        implements TableCellEditor {

    private final JButton botao;
    private final JTable tabela;
    private final String acao;
    private int linha;

    public BotaoEditor(JTable tabela, String acao) {
        this.tabela = tabela;
        this.acao = acao;
        this.botao = new JButton(acao);

        botao.addActionListener(e -> {

            int linhaModelo = tabela.convertRowIndexToModel(linha);

            Object valorCodigo = tabela.getModel().getValueAt(linhaModelo, 0);
            Long codigo = Long.valueOf(valorCodigo.toString());

            ProdutoDao dao = new ProdutoDao();

            if (acao.equals("Remover")) {

                int resposta = JOptionPane.showConfirmDialog(
                    tabela,
                    "Deseja remover este produto?",
                    "Confirmar remoção",
                    JOptionPane.YES_NO_OPTION
                );

                if (resposta == JOptionPane.YES_OPTION) {
                    try {
                        Produto produto = dao.findById(codigo);

                        if (produto != null) {
                            dao.delete(produto);

                            ((DefaultTableModel) tabela.getModel())
                                    .removeRow(linhaModelo);

                            JOptionPane.showMessageDialog(
                                tabela,
                                "Produto removido com sucesso!"
                            );
                        }

                    } catch (Exception ex) {
                        JOptionPane.showMessageDialog(
                            tabela,
                            "Erro ao remover produto: " + ex.getMessage()
                        );
                    }
                }

            } else if (acao.equals("Editar")) {

                try {
                    Produto produto = dao.findById(codigo);

                    if (produto != null) {

                        CadastroProduto cadastro =
                                new CadastroProduto(1, produto);

                        cadastro.addWindowListener(
                            new java.awt.event.WindowAdapter() {
                                @Override
                                public void windowClosed(
                                        java.awt.event.WindowEvent e) {

                                    // Atualiza a tabela após a edição.
                                    ((TelaProduto) tabela.getTopLevelAncestor())
                                            .buscarProdutos();
                                }
                            }
                        );

                        cadastro.setLocationRelativeTo(null);
                        cadastro.setVisible(true);

                    } else {
                        JOptionPane.showMessageDialog(
                                tabela,
                                "Produto não encontrado."
                        );
                    }

                } catch (Exception ex) {
                    JOptionPane.showMessageDialog(
                            tabela,
                            "Erro ao buscar produto: " + ex.getMessage()
                    );
                }
            }

            fireEditingStopped();
        });
    }

    @Override
    public Component getTableCellEditorComponent(
            JTable tabela, Object valor,
            boolean selecionado, int linha, int coluna) {

        this.linha = linha;
        botao.setText(acao);
        return botao;
    }

    @Override
    public Object getCellEditorValue() {
        return acao;
    }
}

