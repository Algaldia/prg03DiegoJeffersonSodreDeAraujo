CREATE TABLE produtos (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    data_validade VARCHAR(255),
    lote VARCHAR(255),
    quantidade_estoque INTEGER NOT NULL,
    marca VARCHAR(255),
    preco REAL
);

